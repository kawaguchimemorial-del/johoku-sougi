export type Hall = {
  slug: string;
  name: string;
  href: string;
  hasDetail: boolean;
  area: string;
  // カード用の短い要約
  summary: string;
  // 外観カバー画像（public 配下の絶対パス・小文字英数字）
  // 写真を用意できていない斎場は未設定にする（他斎場の写真を流用しない）
  image?: string;
  imageAlt?: string;
  // 祭壇イメージ画像
  altar?: string;
  altarAlt?: string;
  // 対応しやすい葬儀形式（カードのタグ表示用）
  forms: string[];
  // 詳細ページのリード文
  lead: string;
  // 詳細ページ本文（斎場ごとに固有）
  intro: string[];
  // 特長・ポイント
  points: string[];
  // この斎場で相談が多い形式の補足
  popularNote: string;
  // 費用の考え方（斎場ごとに少しずつ変える）
  costNote: string;
  // 斎場固有のよくある質問
  faqs: Faq[];
  keywords: string[];
  // 以下は任意（主に戸田斎場の強化用）
  gallery?: { src: string; alt: string; caption: string }[];
  whoFor?: string[]; // どのような方が検討しやすいか
  firstCall?: string[]; // まず電話で伝えるとよいこと
  // 所在地・アクセス（公表情報。実店舗の表現には使わない）
  address?: string;
  access?: string[];
  parking?: string;
  // 式場・火葬炉などの施設構成
  facilities?: string[];
  // 公表されている施設利用料金（目安として掲載）
  fees?: FeeTable[];
  // 料金の出典（いつ時点の公表値かを明記する）
  feeSource?: { label: string; url: string; checked: string };
  // カード下部の対応エリア文言（未設定なら北区・板橋区）
  serviceAreaNote?: string;
  // 詳細ページ下部の関連エリアリンク（未設定なら北区・板橋区）
  relatedAreas?: string[];
};

